"""Private file storage behind one small interface.

Today the files live on local disk. In production (checkpoint 3.7) an S3-compatible bucket
replaces LocalDiskStorage without any caller changing. Rules that hold for every
implementation:
  - keys are generated by the server (new_resume_key), never built from user input
  - there is no public URL: bytes are only returned to code that already authorized the owner
"""

import os
import re
import uuid
from pathlib import Path
from typing import Protocol

from pv_config import Settings

_KEY = re.compile(r"^[a-z]+/[0-9a-f]{32}$")


class StorageError(Exception):
    """A stored file could not be read or written. The message never contains file content."""


class FileStorage(Protocol):
    def put(self, key: str, data: bytes) -> None: ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def exists(self, key: str) -> bool: ...


def new_resume_key() -> str:
    return f"resumes/{uuid.uuid4().hex}"


class LocalDiskStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()

    def _path(self, key: str) -> Path:
        if not _KEY.match(key):
            raise StorageError("Invalid storage key.")
        path = (self._root / key).resolve()
        if self._root not in path.parents:
            raise StorageError("Invalid storage key.")
        return path

    def put(self, key: str, data: bytes) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            temp = path.with_name(path.name + ".part")
            temp.write_bytes(data)
            os.replace(temp, path)  # atomic: readers never see a half-written file
            path.chmod(0o600)
        except OSError as exc:
            raise StorageError("The file could not be stored.") from exc

    def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except OSError as exc:
            raise StorageError("The stored file could not be read.") from exc

    def delete(self, key: str) -> None:
        path = self._path(key)
        try:
            path.unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError("The stored file could not be deleted.") from exc

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


def build_storage(settings: Settings) -> FileStorage:
    return LocalDiskStorage(Path(settings.file_storage_dir))
